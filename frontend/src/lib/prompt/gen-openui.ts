/**
 * Snapshots the OpenUI prompt section and parser schema from src/lib/openui/library.tsx into
 * openui.generated.json. Why: route handlers run on React's react-server build, where
 * @openuidev/react-lang fails at import (it calls createContext at module load), so the chat route
 * cannot import library.tsx. This script runs in plain Node instead.
 *
 * Run: pnpm gen:openui   (also runs before dev, build and eval:routing)
 */
import { writeFileSync, readFileSync, existsSync } from "node:fs";
import path from "node:path";
import { library, openUiPromptSection } from "../openui/library";

const out = path.join(path.dirname(new URL(import.meta.url).pathname), "openui.generated.json");
const schema = library.toJSONSchema() as { $defs?: Record<string, unknown> };
const snapshot = {
  $comment: "Generated by src/lib/prompt/gen-openui.ts from src/lib/openui/library.tsx. Do not edit; run pnpm gen:openui.",
  root: library.root ?? null,
  components: Object.keys(schema.$defs ?? {}),
  promptSection: openUiPromptSection(),
  jsonSchema: schema,
};
const next = JSON.stringify(snapshot, null, 1) + "\n";
const prev = existsSync(out) ? readFileSync(out, "utf8") : "";
if (prev !== next) {
  writeFileSync(out, next);
  console.log(`[gen:openui] wrote ${path.relative(process.cwd(), out)} (${snapshot.components.length} components)`);
} else {
  console.log(`[gen:openui] up to date (${snapshot.components.length} components)`);
}
