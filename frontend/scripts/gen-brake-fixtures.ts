/**
 * Writes src/components/ui-blocks/brake-fixtures.json: the RFQ-02 results of find_offerings and qualify_for_rfq
 * (computed by the same pure functions the skills use, from data/brakes/source), for the /dev/blocks review page.
 *
 *   pnpm tsx scripts/gen-brake-fixtures.ts
 */
import Module from "node:module";
import { writeFileSync } from "node:fs";
import path from "node:path";

const loader = Module as unknown as { _resolveFilename: (request: string, ...rest: unknown[]) => string };
const resolveFilename = loader._resolveFilename;
loader._resolveFilename = function (request: string, ...rest: unknown[]) {
  return resolveFilename.call(this, request === "server-only" ? "next/dist/compiled/server-only/empty.js" : request, ...rest);
};

const ROOT = path.resolve(__dirname, "..");
process.chdir(ROOT);

async function main() {
  const { loadBrakeData } = await import("@/lib/data-api/brakes");
  const { filterOfferings, offeringStats, qualifyRfq } = await import("@/skills/brake-rfq");
  const { rows } = await loadBrakeData();
  const offers = filterOfferings(rows, { product_type: "Rail brake pads" });
  const slim = (o: (typeof offers)[number]) => {
    const { certifications, region, delivery_rating, ...rest } = o;
    void certifications;
    void region;
    void delivery_rating;
    return rest;
  };
  const offerings = { filters: { product_type: "Rail brake pads" }, total: offers.length, supplier_ids: [...new Set(offers.map((o) => o.supplier_id))].sort(), offerings: offers.map(slim), stats: offeringStats(offers), source: "csv" };
  const spec = {
    product_type: "Rail brake pads",
    annual_volume: 30000,
    certifications: ["ISO/TS 22163"],
    copper_free: false,
    max_lead_time_days: 90,
    min_annual_capacity: 30000,
    region: null,
    approved_only: false,
    risk_gate: true,
    max_total_risk_index: 50,
    max_financial_health: 50,
    primary_share: 70,
    monthly_call_off: 2500,
  };
  const rfq = { ...qualifyRfq(rows, spec), focus_id: null, source: "csv" };
  const out = path.join(ROOT, "src/components/ui-blocks/brake-fixtures.json");
  writeFileSync(out, JSON.stringify({ $comment: "Generated by scripts/gen-brake-fixtures.ts from data/brakes/source (RFQ-02). Do not edit.", offerings, rfq }, null, 1) + "\n");
  console.log(`wrote ${path.relative(ROOT, out)}: ${offerings.total} offerings, ${rfq.qualified_ids.length} qualified, award ${rfq.award?.supplier_id}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
